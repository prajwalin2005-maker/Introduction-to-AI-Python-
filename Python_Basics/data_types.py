# Python Data Types

# Integer
age = 21

# Float
height = 5.8

# String
name = "Prajwal"

# Boolean
is_student = True

# List
subjects = ["AI", "Python", "Machine Learning"]

# Tuple
coordinates = (10, 20)

# Set
numbers = {1, 2, 3, 4}

# Dictionary
student = {
    "name": "Prajwal",
    "age": 21,
    "domain": "AI & ML"
}

# None
result = None

print("Integer:", age)
print("Float:", height)
print("String:", name)
print("Boolean:", is_student)
print("List:", subjects)
print("Tuple:", coordinates)
print("Set:", numbers)
print("Dictionary:", student)
print("None:", result)

# Checking data types
print(type(age))
print(type(height))
print(type(name))
print(type(is_student))
print(type(subjects))
print(type(coordinates))
print(type(numbers))
print(type(student))
